"""Generate the full pointer-free team-name preset from its single JSON source.

Like embed_web.py, PlatformIO runs this before every build; cached CMake builds
therefore see source changes. Only changed generated bytes replace the header.
No generated catalogue is stored in LittleFS or checked in beside its source.
"""

import argparse
import hashlib
import json
from pathlib import Path

from generated_file import write_if_changed

SOURCE_RELATIVE_PATH = Path("include/team_names.json")
OUTPUT_RELATIVE_PATH = Path("team_name_asset/team_name_asset.h")
PROVIDERS = ("espn", "openligadb")
TEXT_FIELDS = ("key", "league", "de", "en", "short")


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("duplicate JSON field: %s" % key)
        result[key] = value
    return result


def encode(source):
    """Validate every source field and return its lossless compact encoding."""
    raw = Path(source).read_bytes()
    document = json.loads(raw.decode("utf-8"), object_pairs_hook=unique_object)
    if (not isinstance(document, dict)
            or set(document) != {"format", "version", "clubs"}
            or document["format"] != "football-team-names"
            or type(document["version"]) is not int or document["version"] != 1
            or not isinstance(document["clubs"], list)):
        raise ValueError("unsupported team-name source schema")
    if not 0 < len(document["clubs"]) <= 65535:
        raise ValueError("club count exceeds 16-bit catalogue bounds")
    strings, offsets, aliases, ids, records = bytearray(), {}, [], [], []
    keys, identities = set(), set()

    def intern(value):
        if not isinstance(value, str) or "\0" in value:
            raise ValueError("source strings must be UTF-8 text without NUL")
        if value not in offsets:
            offset = len(strings)
            strings.extend(value.encode("utf-8") + b"\0")
            if len(strings) > 65536:
                raise ValueError("string pool exceeds 16-bit offsets")
            offsets[value] = offset
        return offsets[value]

    for club in document["clubs"]:
        if (not isinstance(club, dict)
                or set(club) != {*TEXT_FIELDS, "aliases", "ids"}):
            raise ValueError("unsupported or missing club field")
        texts = [intern(club[field]) for field in TEXT_FIELDS]
        key = club["key"]
        if not key or key in keys:
            raise ValueError("empty or colliding club key: %s" % key)
        keys.add(key)
        if not isinstance(club["aliases"], list) or len(club["aliases"]) > 255:
            raise ValueError("alias count exceeds 8-bit bounds")
        alias_start = len(aliases)
        aliases.extend(intern(alias) for alias in club["aliases"])
        if not isinstance(club["ids"], dict) or not set(club["ids"]) <= set(PROVIDERS):
            raise ValueError("unsupported provider field")
        starts, counts, present = [], [], 0
        for provider_index, provider in enumerate(PROVIDERS):
            provider_ids = club["ids"].get(provider, [])
            if not isinstance(provider_ids, list) or len(provider_ids) > 255:
                raise ValueError("provider ID count exceeds 8-bit bounds")
            starts.append(len(ids))
            counts.append(len(provider_ids))
            if provider in club["ids"]:
                present |= 1 << provider_index
            for identity in provider_ids:
                if type(identity) is not int or not 0 < identity <= 0xffffffff:
                    raise ValueError("provider ID must fit an unsigned 32-bit integer")
                if (provider, identity) in identities:
                    raise ValueError("colliding %s ID: %d" % (provider, identity))
                identities.add((provider, identity))
                ids.append(identity)
        if max(alias_start, *starts, len(aliases), len(ids)) > 65535:
            raise ValueError("array indices exceed 16-bit bounds")
        records.append((*texts, alias_start, *starts,
                        len(club["aliases"]), *counts, present))
    return {"strings": bytes(strings), "aliases": aliases, "ids": ids,
            "records": records, "sha256": hashlib.sha256(raw).hexdigest()}


def payload_bytes(encoded):
    return (len(encoded["strings"]) + 20 * len(encoded["records"])
            + 2 * len(encoded["aliases"]) + 4 * len(encoded["ids"]))


def render_header(source):
    encoded = encode(source)
    lines = ["// Generated by scripts/embed_team_names.py; do not edit.",
             "// Full source SHA256: " + encoded["sha256"],
             'constexpr char kSourceSha256[] = "' + encoded["sha256"] + '";',
             "constexpr unsigned char kStrings[] = {"]
    values = encoded["strings"]
    lines.extend(",".join(map(str, values[i:i + 24])) + ","
                 for i in range(0, len(values), 24))
    lines += ["};", "constexpr Record kClubs[] = {"]
    lines.extend("{" + ",".join(map(str, record)) + "},"
                 for record in encoded["records"])
    lines += ["};"]
    for ctype, name, values in (("uint16_t", "kAliases", encoded["aliases"]),
                                ("uint32_t", "kIds", encoded["ids"])):
        # An empty collection uses no payload bytes; std::array<T, 0> can add
        # a byte and empty C arrays are nonstandard. Reject until explicitly
        # supported instead of silently changing the measured representation.
        if not values:
            raise ValueError("empty %s array needs a revised encoding" % name)
        lines += ["constexpr " + ctype + " " + name + "[] = {"]
        lines.extend(",".join(map(str, values[i:i + 16])) + ","
                     for i in range(0, len(values), 16))
        lines += ["};"]
    lines += ["constexpr std::size_t kPayloadBytes = sizeof(kStrings) +",
              "    sizeof(kClubs) + sizeof(kAliases) + sizeof(kIds);",
              "static_assert(kPayloadBytes == %d);" % payload_bytes(encoded), ""]
    return "\n".join(lines), payload_bytes(encoded)


def prepare_header(source, build_dir):
    text, size = render_header(source)
    output = Path(build_dir) / OUTPUT_RELATIVE_PATH
    return output, write_if_changed(output, text.encode("utf-8")), size


def run_platformio(env):
    source = Path(env.subst("$PROJECT_DIR")) / SOURCE_RELATIVE_PATH
    try:
        output, changed, size = prepare_header(source, env.subst("$BUILD_DIR"))
    except (OSError, UnicodeError, ValueError) as error:
        print("Error (team-name asset): %s" % error)
        env.Exit(1)
        return
    if changed:
        print("team-name asset: generated %s (%d bytes payload)" % (output, size))


if "Import" in globals():
    Import("env")
    run_platformio(env)
elif __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("build_dir", type=Path)
    args = parser.parse_args()
    try:
        output, changed, size = prepare_header(args.source, args.build_dir)
    except (OSError, UnicodeError, ValueError) as error:
        parser.exit(1, "Error (team-name asset): %s\n" % error)
    print("%s: %s (%d bytes payload)"
          % ("generated" if changed else "unchanged", output, size))
