"""Generate lossless 4-bpp LVGL subsets; normal builds need no Pillow."""
from pathlib import Path
import hashlib
import subprocess
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/fonts/Montserrat.ttf"
SHA256 = "1e2c44ef8c956ed66998649d8c832d221e22c04eaab63c044f18eb05d1c63b7c"
LATIN = sorted(set(range(32, 127)) | set(range(160, 256)) |
               {ord(c) for c in "ĀāĆćČčĐđĞğıŁłŃńŐőŘřŚśŞşŠšŰűŹźŻżŽž’–—…"})


def compress(pixels):
    """LVGL RLE without prefilter: two equal nibbles start a repeated run."""
    bits = []

    def put(value, count):
        bits.extend((value >> bit) & 1 for bit in range(count - 1, -1, -1))

    repeated, previous, repeats = False, None, 0
    for value in pixels:
        if not repeated:
            put(value, 4)
            repeated = value == previous
            previous, repeats = value, 0
        elif value != previous:
            put(0, 1)
            put(value, 4)
            repeated, previous, repeats = False, value, 0
        elif repeats == 10:
            # A zero long-run count returns to literal mode. Limiting the
            # encoder to this form keeps one deterministic stream per glyph.
            put(1, 1)
            put(0, 6)
            put(value, 4)
            repeated, previous, repeats = False, value, 0
        else:
            put(1, 1)
            repeats += 1
    bits.extend([0] * (-len(bits) % 8))
    return bytes(sum(bits[i + j] << (7 - j) for j in range(8))
                 for i in range(0, len(bits), 8))


def generate(size, points, name, *, destination=None, compressed=True):
    font = ImageFont.truetype(str(SOURCE), size)
    font.set_variation_by_axes([500])
    bitmap, descriptors = bytearray(), [(0, 0, 0, 0, 0, 0)]
    above = below = 0
    for cp in points:
        letter = chr(cp)
        left, top, right, bottom = font.getbbox(letter, anchor="ls")
        width, height = right - left, bottom - top
        above, below = max(above, -top), max(below, bottom)
        descriptors.append((len(bitmap), round(font.getlength(letter) * 16),
                            width, height, left, -bottom))
        image = Image.new("L", (max(1, width), max(1, height)))
        ImageDraw.Draw(image).text((-left, -top), letter, font=font, fill=255, anchor="ls")
        pixels = [round(v * 15 / 255) for v in image.get_flattened_data()] if width and height else []
        if compressed:
            bitmap.extend(compress(pixels))
        else:
            for offset in range(0, len(pixels), 2):
                bitmap.append((pixels[offset] << 4) | (pixels[offset + 1] if offset + 1 < len(pixels) else 0))
    rows = ["/* Generated by scripts/build_fonts.py; Montserrat, SIL OFL 1.1. */",
            '#include "ui_font_rle.h"' if compressed else '#include "lvgl.h"',
            "static const uint8_t glyph_bitmap[] = {"]
    rows += ["  " + ", ".join(f"0x{v:02x}" for v in bitmap[i:i+16]) + "," for i in range(0, len(bitmap), 16)]
    rows += ["};", "static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {"]
    for index, advance, width, height, x, y in descriptors:
        rows.append(f"  {{.bitmap_index={index}, .adv_w={advance}, .box_w={width}, .box_h={height}, .ofs_x={x}, .ofs_y={y}}},")
    start = points[0]
    rows += ["};", "static const uint16_t unicode_list[] = {" + ",".join(str(cp-start) for cp in points) + "};",
             "static const lv_font_fmt_txt_cmap_t cmaps[] = {",
             f"  {{.range_start={start}, .range_length={points[-1]-start+1}, .glyph_id_start=1, .unicode_list=unicode_list, .list_length={len(points)}, .type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}", "};",
             ("static const ui_font_rle_dsc_t font_dsc = {.text={.glyph_bitmap=glyph_bitmap, .glyph_dsc=glyph_dsc, .cmaps=cmaps, .cmap_num=1, .bpp=4, .bitmap_format=LV_FONT_FMT_TXT_COMPRESSED_NO_PREFILTER}, .bitmap_bytes=sizeof(glyph_bitmap), .glyph_count=sizeof(glyph_dsc)/sizeof(glyph_dsc[0])};"
              if compressed else "static const lv_font_fmt_txt_dsc_t font_dsc = {.glyph_bitmap=glyph_bitmap, .glyph_dsc=glyph_dsc, .cmaps=cmaps, .cmap_num=1, .bpp=4, .bitmap_format=LV_FONT_FMT_TXT_PLAIN};"),
             "static bool glyph(const lv_font_t* font, lv_font_glyph_dsc_t* out, uint32_t cp, uint32_t next) {",
             "  return lv_font_get_glyph_dsc_fmt_txt(font, out, cp, next) || lv_font_get_glyph_dsc_fmt_txt(font, out, '?', 0);", "}",
             f"const lv_font_t {name} = {{.get_glyph_dsc=glyph, .get_glyph_bitmap={'ui_font_rle_bitmap' if compressed else 'lv_font_get_bitmap_fmt_txt'}, .line_height={above+below}, .base_line={below}, .cap_height={-font.getbbox('H', anchor='ls')[1]}, .x_height={-font.getbbox('x', anchor='ls')[1]}, .static_bitmap={0 if compressed else 1}, .dsc=&font_dsc}};", ""]
    destination = destination or ROOT / f"components/ui/fonts/{name}.c"
    destination.write_text("\n".join(rows))
    formatter = ROOT / ".venv-tools/bin/clang-format"
    if formatter.exists():
        subprocess.run([str(formatter), "-i", str(destination)], check=True)
    print(f"{name}: {len(points)} glyphs, bitmap {len(bitmap)} B, line {above+below} px")


if __name__ == "__main__":
    if hashlib.sha256(SOURCE.read_bytes()).hexdigest() != SHA256:
        raise SystemExit("Font source hash differs; review source/licence before regenerating")
    for px in (12, 14, 18):
        generate(px, LATIN, f"ui_font_text_{px}")
    generate(48, sorted({ord(c) for c in " 0123456789:-?"}), "ui_font_score_48")
